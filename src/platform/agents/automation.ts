function header(tc: TestCase, ds: Dataset, rules: BusinessRule[], scriptId: string, origin: string) {
  const r = rules.filter((b) => tc.ruleIds.includes(b.id));
  return `/**
 * ${scriptId} — generated by the ${AGENT} (${origin})
 * Test case:   ${tc.id} [${tc.type}/${tc.channel}] ${tc.title}
 * Requirement: ${tc.requirementIds.join(', ')}
 * Rule:        ${r.map((b) => `${b.id} ${b.text}`).join(' | ')}
 * Dataset:     ${ds.id} (SYNTHETIC, seed ${ds.provenance.seed})
 * Expected:    ${tc.expected.success ? `success, status ${tc.expected.status}` : `rejected with ${tc.expected.errorCode}`}
 */`;
}

export function specSource(tc: TestCase, ds: Dataset, rules: BusinessRule[], scriptId: string, origin: string): string {
  const rule = tc.ruleIds[0];
  const tags = JSON.stringify([...tc.ruleIds, ...tc.requirementIds, tc.type, tc.channel].map((t) => `@${t}`));
  const title = `${tc.id} ${tc.title}`.replace(/'/g, "\\'");
  const pattern = tc.expected.confirmationPattern ?? '^CNF-[A-Z0-9]{8}$';
  const lines: string[] = [header(tc, ds, rules, scriptId, origin)];
  if (tc.channel === 'api') {
    lines.push(`import { test, expect${tc.expected.success ? ', GET_RESERVATION, Reservation' : ''} } from '../support/aqe';

test('${title}', { tag: ${tags} }, async ({ aqe }) => {
  const ds = aqe.dataset('${ds.id}');
  const result = await aqe.createReservation(ds.values);`);
    if (tc.expected.success) {
      lines.push(`  expect(result.errors, '${rule}: validation errors').toEqual([]);
  expect(result.success, '${rule}: createReservation.success').toBe(true);
  expect(result.reservation?.confirmationNumber, 'BR-005: confirmation number format').toMatch(/${pattern}/);
  expect(result.reservation?.status, 'reservation status').toBe('${tc.expected.status}');
  expect(result.reservation?.payment.paymentToken, 'payment token returned masked').toMatch(/^tok_\\*{4}/);
  const read = await aqe.gql<{ reservation: Reservation | null }>(GET_RESERVATION, { confirmationNumber: result.reservation!.confirmationNumber }, 'reservation');
  expect(read.reservation?.reservationId, 'reservation is retrievable by confirmation number').toBe(result.reservation!.reservationId);
});`);
    } else {
      lines.push(`  expect(result.success, '${rule}: createReservation.success').toBe(false);
  expect(result.reservation, '${rule}: no reservation created').toBeNull();
  expect(result.errors.map((e) => e.code), '${rule}: error codes').toContain('${tc.expected.errorCode}');
});`);
    }
  } else {
    lines.push(`import { test, expect } from '../support/aqe';
import { ReservationConsole } from '../support/reservation-console';

test('${title}', { tag: ${tags} }, async ({ page, aqe }) => {
  const ds = aqe.dataset('${ds.id}');
  const ui = new ReservationConsole(page);
  await ui.open();
  await ui.fillCreate(ds.values);
  await ui.submitCreate();
  await aqe.screenshot(page, 'create-outcome');`);
    if (!tc.expected.success) {
      lines.push(`  await expect(ui.outcome(), '${rule}: create outcome').toHaveAttribute('data-testid', 'error-toast');
  await expect(ui.error('${tc.expected.errorCode}'), '${rule}: ${tc.expected.errorCode} shown').toBeVisible();
  await expect(page.getByTestId('confirmation-number'), '${rule}: no confirmation number issued').toHaveCount(0);
});`);
    } else {
      lines.push(`  await expect(ui.outcome(), '${rule}: create outcome').toHaveAttribute('data-testid', 'success-toast');
  const confirmation = (await page.getByTestId('confirmation-number').textContent()) ?? '';
  expect(confirmation, 'BR-005: confirmation number format').toMatch(/${pattern}/);
  await expect(page.getByTestId('reservation-status')).toHaveText('CONFIRMED');`);
      if (tc.flow === 'create-search-cancel') {
        lines.push(`  const rows = await ui.search(confirmation);
  await expect(rows, 'search finds the reservation').toHaveCount(1);
  await expect(rows.first().getByTestId('row-status')).toHaveText('CONFIRMED');
  await aqe.screenshot(page, 'search-result');
  const toast = await ui.cancel(confirmation, 'Synthetic cancellation for automated test');
  await expect(toast, 'cancel outcome').toHaveAttribute('data-testid', 'success-toast');
  const after = await ui.search(confirmation);
  await expect(after.first().getByTestId('row-status'), 'status after cancel').toHaveText('${tc.expected.status}');
  await aqe.screenshot(page, 'after-cancel');`);
      }
      lines.push('});');
    }
  }
  return `${lines.join('\n')}\n`;
}

/** Writes the suite into <dir> and returns script records linked to test cases and datasets. */
export function generateSuite(dir: string, home: string, testCases: TestCase[], datasets: Dataset[], rules: BusinessRule[], origin: string, idPrefix = 'AS-'): AutomationScript[] {
  fs.mkdirSync(path.join(dir, 'tests'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'support'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'data'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'playwright.config.ts'), PLAYWRIGHT_CONFIG);
  fs.writeFileSync(path.join(dir, 'support', 'aqe.ts'), SUPPORT_AQE);
  fs.writeFileSync(path.join(dir, 'support', 'reservation-console.ts'), SUPPORT_CONSOLE);
  return testCases.map((tc) => {
    const ds = datasets.find((d) => d.testCaseId === tc.id)!;
    const id = `${idPrefix}${tc.id}`;
    fs.writeFileSync(path.join(dir, 'data', `${ds.id}.json`), `${JSON.stringify({ id: ds.id, classification: ds.classification, provenance: ds.provenance, values: ds.values }, null, 2)}\n`);
    const source = specSource(tc, ds, rules, id, origin);
    const file = path.join(dir, 'tests', `${tc.id}.${tc.channel}.spec.ts`);
    fs.writeFileSync(file, source);
    return { id, testCaseId: tc.id, datasetId: ds.id, ruleIds: tc.ruleIds, requirementIds: tc.requirementIds, channel: tc.channel, file: rel(home, file), sha256: sha256(source) };
  });
}
